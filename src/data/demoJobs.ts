export function getJobById(id: string): JobVacancy | undefined {
  return DEMO_VACANCIES.find((job) => job.id === id || job.slug === id);
}

export function getJobsBySector(sector: 'central' | 'state'): JobVacancy[] {
  return DEMO_VACANCIES.filter((job) => job.sector === sector);
}

export function getJobsByStateCode(stateCode: string): JobVacancy[] {
  return DEMO_VACANCIES.filter(
    (job) => job.stateCode?.toLowerCase() === stateCode.toLowerCase()
  );
}

export function getJobsByCentralCategory(cat: string): JobVacancy[] {
  return DEMO_VACANCIES.filter(
    (job) =>
      job.sector === 'central' &&
      job.centralCategory?.toLowerCase() === cat.toLowerCase()
  );
}
